LANGS = ["node","python","php","ruby","go","rust","java","dotnet","kotlin","deno","bun",
         "swift","dart","scala","julia","zig"]

def pick(lang, when):
    cur = TABLES[lang][0][0]      # chưa ra mắt -> dùng bản đầu tiên của ngôn ngữ đó
    for line, rel in TABLES[lang]:
        if d(rel) <= when: cur = line
    return cur

def rust(when):
    # Rust ra bản 1.N mỗi 6 tuần, 1.0 = 2015-05-15 (1.8 = 2016-04-14 ✓)
    return "1.%d.0" % ((when - date(2015, 5, 15)).days // 42)

rows = []
for i in range(N):
    tag = "14.5" if i == N - 1 else "%d.0" % (i + 1)
    when = START + timedelta(days=round((END - START).days * i / (N - 1)))
    look = min(when, CLAMP)
    row = {"tag": tag, "date": when.isoformat()}
    for lang in LANGS:
        row[lang] = rust(look) if lang == "rust" else pick(lang, look)
    if tag == "14.5":   # bản mới nhất
        row.update(go="latest", rust="stable", kotlin="latest", deno="latest", bun="latest",
                   swift="latest", dart="latest", scala="latest", julia="latest", zig="latest")
    rows.append(row)

